// Link previews: the pure half of scripts/build-og.mjs.
//
// Everything here is string-in, string-out so it can be unit tested without a
// browser: which pages get a card, what the card says, the <meta> block that
// goes into each page's <head>, and where that block is inserted.

import { createHash } from 'node:crypto';
import * as cheerio from 'cheerio';
import { clean } from './text.mjs';

export const SITE = 'https://esc.studentorg.berkeley.edu';
export const SITE_NAME = 'Engineering Student Council at UC Berkeley';
export const THEME_COLOR = '#002676';
export const OG_DIR = 'images/og';
export const CARD_WIDTH = 1200;
export const CARD_HEIGHT = 630;

export const START = '<!-- link-preview:start -->';
export const END = '<!-- link-preview:end -->';
const NOTE =
  '<!-- Generated by `npm run build:og`; edit data/search/pages.json, not this block. -->';

/**
 * Pages the build leaves alone. Their <head> is not touched and no card is
 * rendered, so the build can never cause a merge conflict on them.
 */
// Pages to leave without a card while someone is mid-rewrite on another branch:
// ['page.html', 'reason']. Remove the entry once that work merges, then run
// `npm run build:og`.
export const SKIP = new Map([]);

/** The generic card, for anything that doesn't have its own. */
export const DEFAULT_CARD = { slug: 'default', title: 'Engineering Student Council', trail: [] };

/** Escape a value for use inside a double-quoted HTML attribute. */
export function escapeAttr(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/** Absolute public URL of a page; index.html is served as its folder. */
export function pageUrl(page) {
  const path = page.replace(/(^|\/)index\.html$/, '$1');
  return `${SITE}/${path.split('/').map(encodeURIComponent).join('/')}`;
}

/** File-name-safe identifier for a page's card: about.html → about. */
export function slugFor(page) {
  return page
    .replace(/\.html$/i, '')
    .replace(/\//g, '--')
    .replace(/[^A-Za-z0-9_-]+/g, '-');
}

export const imagePath = (slug) => `${OG_DIR}/${slug}.png`;
export const imageUrl = (slug) => `${SITE}/${imagePath(slug)}`;

/** The page's own <title> and meta description, used when the index has no record. */
export function readHead(html) {
  const $ = cheerio.load(html);
  return {
    title: clean($('head > title').first().text()),
    description: clean($('meta[name="description"]').first().attr('content')),
  };
}

/**
 * What a page's preview says. `record` is the page's entry in
 * assets/search/index.json (kind=page), if any; `html` is the page source.
 */
export function cardFor(page, { record, html = '', fallbackDescription = '' } = {}) {
  const head = readHead(html);
  const home = page === 'index.html';
  const title = home
    ? DEFAULT_CARD.title
    : clean(record?.title) || head.title || DEFAULT_CARD.title;
  const slug = slugFor(page);
  return {
    page,
    slug,
    title: home ? SITE_NAME : title,
    cardTitle: title,
    trail: home ? [] : (record?.trail ?? []).map(clean).filter(Boolean),
    description: clean(record?.description) || head.description || fallbackDescription,
    url: pageUrl(page),
    image: imageUrl(slug),
    alt: home ? SITE_NAME : `${title} · ${SITE_NAME}`,
  };
}

/** The <head> block for one card, one tag per line. */
export function renderBlock(card, { indent = '', eol = '\n' } = {}) {
  const meta = (attr, key, value) => `<meta ${attr}="${key}" content="${escapeAttr(value)}" />`;
  const lines = [
    START,
    NOTE,
    meta('property', 'og:type', 'website'),
    meta('property', 'og:site_name', SITE_NAME),
    meta('property', 'og:title', card.title),
    meta('property', 'og:description', card.description),
    meta('property', 'og:url', card.url),
    meta('property', 'og:image', card.image),
    meta('property', 'og:image:type', 'image/png'),
    meta('property', 'og:image:width', CARD_WIDTH),
    meta('property', 'og:image:height', CARD_HEIGHT),
    meta('property', 'og:image:alt', card.alt),
    meta('name', 'twitter:card', 'summary_large_image'),
    meta('name', 'twitter:title', card.title),
    meta('name', 'twitter:description', card.description),
    meta('name', 'twitter:image', card.image),
    meta('name', 'twitter:image:alt', card.alt),
    meta('name', 'theme-color', THEME_COLOR),
    END,
  ];
  return lines.map((line) => indent + line + eol).join('');
}

/** The line ending a file already uses, so edits never mix CRLF and LF. */
export function detectEol(text) {
  return /\r\n/.test(text) ? '\r\n' : '\n';
}

const lineStart = (text, i) => text.lastIndexOf('\n', i - 1) + 1;
const indentAt = (text, i) => /^[ \t]*/.exec(text.slice(lineStart(text, i)))[0];

/** Index just past the end of the line containing `i` (after its line ending). */
function lineEnd(text, i) {
  const nl = text.indexOf('\n', i);
  return nl === -1 ? text.length : nl + 1;
}

const VIEWPORT = /<meta\b[^>]*\bname\s*=\s*["']?viewport\b[^>]*>/i;
const CHARSET = /<meta\b[^>]*\bcharset\b[^>]*>/i;

/**
 * Where a fresh block goes: on the line after the viewport <meta>, else after
 * <meta charset>, else on its own line just before </head>. Returns the
 * insertion offset, the indentation to use, and `before`: a line break to
 * add first when the anchor shares its line with </head>.
 */
export function findPlacement(html) {
  const headEnd = html.search(/<\/head\s*>/i);
  if (headEnd === -1) throw new Error('no </head> found');
  const head = html.slice(0, headEnd);
  const eol = detectEol(html);
  for (const [rule, anchor] of [
    ['viewport', VIEWPORT],
    ['charset', CHARSET],
  ]) {
    const match = anchor.exec(head);
    if (!match) continue;
    const at = lineEnd(html, match.index + match[0].length);
    const indent = indentAt(html, match.index);
    return at > headEnd
      ? { rule, at: headEnd, indent, before: eol }
      : { rule, at, indent, before: '' };
  }
  const start = lineStart(html, headEnd);
  const closing = indentAt(html, headEnd);
  const indent = closing + (closing.includes('\t') || !closing ? '\t' : '  ');
  return /^[ \t]*$/.test(html.slice(start, headEnd))
    ? { rule: 'head', at: start, indent, before: '' }
    : { rule: 'head', at: headEnd, indent, before: eol };
}

/** Location of an existing block (whole lines, including indentation and line ending). */
export function findBlock(html) {
  const first = html.indexOf(START);
  if (first === -1) return null;
  if (html.indexOf(START, first + START.length) !== -1) {
    throw new Error('more than one link-preview block');
  }
  const close = html.indexOf(END, first);
  if (close === -1) throw new Error('link-preview block is missing its end marker');
  return {
    start: lineStart(html, first),
    end: lineEnd(html, close),
    indent: indentAt(html, first),
  };
}

/**
 * Insert or refresh the link-preview block. Running it again on its own
 * output changes nothing; every byte outside the block is left as it was.
 */
export function injectBlock(html, card) {
  const eol = detectEol(html);
  const existing = findBlock(html);
  if (existing) {
    const block = renderBlock(card, { indent: existing.indent, eol });
    return html.slice(0, existing.start) + block + html.slice(existing.end);
  }
  const { at, indent, before } = findPlacement(html);
  return html.slice(0, at) + before + renderBlock(card, { indent, eol }) + html.slice(at);
}

/** Pull the generated tags back out of a page (for tests and checks). */
export function readBlock(html) {
  const found = findBlock(html);
  if (!found) return null;
  const $ = cheerio.load(html.slice(found.start, found.end));
  const tags = {};
  $('meta').each((_, el) => {
    const key = $(el).attr('property') || $(el).attr('name');
    tags[key] = $(el).attr('content');
  });
  return tags;
}

/** Fingerprint of everything that affects a card's pixels. */
export function cardHash(card, assets) {
  return createHash('sha256')
    .update(JSON.stringify({ title: card.cardTitle ?? card.title, trail: card.trail, assets }))
    .digest('hex')
    .slice(0, 16);
}
